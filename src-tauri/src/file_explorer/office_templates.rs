//! Minimal valid empty Office Open XML documents (.docx/.xlsx/.pptx), built
//! as a raw zip of the smallest XML skeleton each format needs to open
//! cleanly in Word/Excel/PowerPoint — not just an empty file with the
//! right extension. Verified against the OOXML part structure each app
//! expects (`[Content_Types].xml`, `_rels/.rels`, and one part per format).

use std::io::Write;
use zip::write::SimpleFileOptions;
use zip::ZipWriter;

fn write_zip(entries: &[(&str, &str)]) -> Result<Vec<u8>, String> {
  let mut buffer = Vec::new();
  {
    let cursor = std::io::Cursor::new(&mut buffer);
    let mut zip = ZipWriter::new(cursor);
    let options = SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
    for (name, contents) in entries {
      zip.start_file(*name, options).map_err(|e| e.to_string())?;
      zip.write_all(contents.as_bytes()).map_err(|e| e.to_string())?;
    }
    zip.finish().map_err(|e| e.to_string())?;
  }
  Ok(buffer)
}

const RELS: &str = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="{TARGET}"/>
</Relationships>"#;

pub fn empty_docx() -> Result<Vec<u8>, String> {
  let content_types = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>"#;
  let rels = RELS.replace("{TARGET}", "word/document.xml");
  let document = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    <w:p/>
    <w:sectPr/>
  </w:body>
</w:document>"#;
  write_zip(&[
    ("[Content_Types].xml", content_types),
    ("_rels/.rels", &rels),
    ("word/document.xml", document),
  ])
}

pub fn empty_xlsx() -> Result<Vec<u8>, String> {
  let content_types = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
  <Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
</Types>"#;
  let rels = RELS.replace("{TARGET}", "xl/workbook.xml");
  let workbook = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="Sheet1" sheetId="1" r:id="rId1"/>
  </sheets>
</workbook>"#;
  let workbook_rels = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>"#;
  let sheet = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData/>
</worksheet>"#;
  write_zip(&[
    ("[Content_Types].xml", content_types),
    ("_rels/.rels", &rels),
    ("xl/workbook.xml", workbook),
    ("xl/_rels/workbook.xml.rels", workbook_rels),
    ("xl/worksheets/sheet1.xml", sheet),
  ])
}

